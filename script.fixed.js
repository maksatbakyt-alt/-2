function toggleCompare(id, isChecked) {
    if (isChecked) {
        const found = hybrids.find(h => h.id === id);
        if (found && !compareList.some(c => c.id === id)) compareList.push(found);
    } else {
        compareList = compareList.filter(h => h.id !== id);
    }
    renderComparison();
}

